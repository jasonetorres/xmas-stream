import fs from "node:fs";
import path from "node:path";
import { AsyncLocalStorage } from "node:async_hooks";

const als = new AsyncLocalStorage();

function schema(dialect) {
  const pk = dialect === "pg" ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY";
  const blob = dialect === "pg" ? "BYTEA" : "BLOB";
  return [
    `CREATE TABLE IF NOT EXISTS sponsors (
      id ${pk},
      slug TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      tier TEXT NOT NULL,
      contact_name TEXT NOT NULL DEFAULT '',
      x_handle TEXT NOT NULL DEFAULT '',
      prize_details TEXT NOT NULL DEFAULT '',
      not_before INTEGER,
      url TEXT NOT NULL DEFAULT '',
      talking_points TEXT NOT NULL DEFAULT '',
      shipping TEXT NOT NULL DEFAULT '',
      credit TEXT NOT NULL DEFAULT '',
      code_hash TEXT NOT NULL UNIQUE,
      code_enc TEXT NOT NULL,
      created_at TEXT NOT NULL,
      assets_updated_at TEXT
    )`,
    `CREATE TABLE IF NOT EXISTS logos (
      id ${pk},
      sponsor_id INTEGER NOT NULL REFERENCES sponsors(id) ON DELETE CASCADE,
      filename TEXT NOT NULL,
      mime TEXT NOT NULL,
      bytes ${blob} NOT NULL,
      created_at TEXT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS bookings (
      id ${pk},
      sponsor_id INTEGER NOT NULL UNIQUE REFERENCES sponsors(id) ON DELETE CASCADE,
      start_min INTEGER NOT NULL,
      end_min INTEGER NOT NULL,
      gift_drop INTEGER NOT NULL DEFAULT 0,
      hot_seat INTEGER NOT NULL DEFAULT 0,
      guest_name TEXT NOT NULL DEFAULT '',
      set_by TEXT NOT NULL DEFAULT 'sponsor',
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    )`,
    "CREATE INDEX IF NOT EXISTS bookings_range ON bookings (start_min, end_min)",
    "CREATE INDEX IF NOT EXISTS logos_sponsor ON logos (sponsor_id)",
  ];
}

function normalizeRow(row) {
  if (!row) return null;
  const out = {};
  for (const [key, value] of Object.entries(row)) {
    out[key] = typeof value === "bigint" ? Number(value) : value;
  }
  return out;
}

function toPg(sql) {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

class Base {
  constructor() {
    this.chain = Promise.resolve();
  }

  enqueue(fn) {
    const run = this.chain.then(fn, fn);
    this.chain = run.then(
      () => {},
      () => {}
    );
    return run;
  }

  get(sql, params = []) {
    if (als.getStore()) return this._get(sql, params);
    return this.enqueue(() => this._get(sql, params));
  }

  all(sql, params = []) {
    if (als.getStore()) return this._all(sql, params);
    return this.enqueue(() => this._all(sql, params));
  }

  run(sql, params = []) {
    if (als.getStore()) return this._run(sql, params);
    return this.enqueue(() => this._run(sql, params));
  }

  tx(fn) {
    return this.enqueue(() => this._tx(fn));
  }
}

class SqliteDb extends Base {
  constructor(file, DatabaseSync) {
    super();
    this.dialect = "sqlite";
    this.file = file;
    if (file !== ":memory:") fs.mkdirSync(path.dirname(file), { recursive: true });
    this.db = new DatabaseSync(file);
    this.db.exec("PRAGMA foreign_keys = ON");
    this.db.exec("PRAGMA busy_timeout = 5000");
    if (file !== ":memory:") this.db.exec("PRAGMA journal_mode = WAL");
  }

  _get(sql, params) {
    return normalizeRow(this.db.prepare(sql).get(...params));
  }

  _all(sql, params) {
    return this.db.prepare(sql).all(...params).map((row) => normalizeRow(row));
  }

  _run(sql, params) {
    const info = this.db.prepare(sql).run(...params);
    return {
      changes: Number(info.changes || 0),
      id: info.lastInsertRowid == null ? null : Number(info.lastInsertRowid),
    };
  }

  async _tx(fn) {
    this.db.exec("BEGIN IMMEDIATE");
    try {
      const result = await als.run({ inTx: true }, fn);
      this.db.exec("COMMIT");
      return result;
    } catch (err) {
      try {
        this.db.exec("ROLLBACK");
      } catch {
        /* already closed */
      }
      throw err;
    }
  }

  async migrate() {
    for (const stmt of schema("sqlite")) await this.enqueue(() => this.db.exec(stmt));
  }

  close() {
    this.db.close();
  }
}

class PostgresDb extends Base {
  constructor(pool) {
    super();
    this.dialect = "pg";
    this.pool = pool;
  }

  runner() {
    return als.getStore()?.client || this.pool;
  }

  async _get(sql, params) {
    const res = await this.runner().query(toPg(sql), params);
    return res.rows[0] || null;
  }

  async _all(sql, params) {
    const res = await this.runner().query(toPg(sql), params);
    return res.rows;
  }

  async _run(sql, params) {
    const res = await this.runner().query(toPg(sql), params);
    return { changes: res.rowCount, id: res.rows[0]?.id ?? null };
  }

  async _tx(fn) {
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      await client.query("SELECT pg_advisory_xact_lock(842018)");
      const result = await als.run({ client }, fn);
      await client.query("COMMIT");
      return result;
    } catch (err) {
      try {
        await client.query("ROLLBACK");
      } catch {
        /* connection already failed */
      }
      throw err;
    } finally {
      client.release();
    }
  }

  async migrate() {
    for (const stmt of schema("pg")) await this.enqueue(() => this.pool.query(stmt));
  }

  async close() {
    await this.pool.end();
  }
}

export async function openDatabase({ databaseUrl, sqlitePath }) {
  if (databaseUrl) {
    const pg = await import("pg");
    const Pool = pg.default?.Pool || pg.Pool;
    const pool = new Pool({ connectionString: databaseUrl });
    const db = new PostgresDb(pool);
    await pool.query("SELECT 1");
    return db;
  }
  const { DatabaseSync } = await import("node:sqlite");
  return new SqliteDb(sqlitePath, DatabaseSync);
}
